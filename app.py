
import streamlit as st
import pandas as pd
import numpy as np
from pathlib import Path
import matplotlib.pyplot as plt

st.set_page_config(
    page_title="Jump Rope Monitor",
    page_icon="🏃",
    layout="wide"
)

st.title("Jump Rope Motion Monitor")
st.caption("IMU Signal Processing Dashboard · Prototype")

st.info(
    "This prototype displays processed simulated data. "
    "Real-time hardware monitoring will be added after IMU data is available."
)

# Load local CSV or upload another file
uploaded_file = st.sidebar.file_uploader(
    "Upload IMU analysis CSV",
    type=["csv"]
)

if uploaded_file is not None:
    df = pd.read_csv(uploaded_file)
else:
    csv_path = Path("analysis_result.csv")

    if csv_path.exists():
        df = pd.read_csv(csv_path)
    else:
        st.warning(
            "analysis_result.csv was not found. "
            "Run peak_detection.py first, or upload a CSV file."
        )
        st.stop()

# Check required columns
required_columns = [
    "time",
    "raw_acceleration",
    "filtered_acceleration",
    "is_peak"
]

if not all(col in df.columns for col in required_columns):
    st.error(
        "CSV format is incorrect. Please use analysis_result.csv "
        "generated by peak_detection.py."
    )
    st.stop()

df = df.sort_values("time").reset_index(drop=True)


# Calculate duration and detected peak count
duration = float(df["time"].max() - df["time"].min())
peak_count = int(df["is_peak"].sum())

# Get the timestamps of detected peaks
peak_times = (
    df.loc[df["is_peak"] == 1, "time"]
    .sort_values()
    .to_numpy()
)

# Calculate frequency using intervals between adjacent peaks
if len(peak_times) >= 2:
    intervals = np.diff(peak_times)
    valid_intervals = intervals[intervals > 0]

    if len(valid_intervals) > 0:
        average_interval = np.mean(valid_intervals)
        frequency = 1.0 / average_interval
        rate = frequency * 60
    else:
        frequency = 0.0
        rate = 0.0
else:
    frequency = 0.0
    rate = 0.0


# Summary cards

col1, col2, col3, col4, col5 = st.columns(5)

col1.metric("Detected Peaks", peak_count)
col2.metric("Estimated Rate", f"{rate:.1f}", "cycles/min")

if len(peak_times) >= 2 and len(valid_intervals) > 0:
    col3.metric(
        "Average Peak Interval",
        f"{average_interval:.3f}",
        "seconds"
    )
else:
    col3.metric("Average Peak Interval", "N/A")

col4.metric("Duration", f"{duration:.1f}", "seconds")
col5.metric("Sampling Points", len(df))


st.divider()

# Signal visualization

st.subheader("Acceleration Signal")

# Get detected peak locations
peak_df = df[df["is_peak"] == 1]

# Create the plot
fig, ax = plt.subplots(figsize=(12, 5))

# Plot raw acceleration
ax.plot(
    df["time"],
    df["raw_acceleration"],
    color="lightskyblue",
    linewidth=1,
    alpha=0.8,
    label="Raw Acceleration"
)

# Plot filtered acceleration
ax.plot(
    df["time"],
    df["filtered_acceleration"],
    color="royalblue",
    linewidth=1.5,
    label="Filtered Acceleration"
)

# Mark detected peaks with red dots
ax.scatter(
    peak_df["time"],
    peak_df["filtered_acceleration"],
    color="red",
    s=55,
    zorder=5,
    label="Detected Peaks"
)

# Add labels and styling
ax.set_xlabel("Time (s)")
ax.set_ylabel("Acceleration")
ax.set_title("Acceleration Signal with Detected Peaks")
ax.grid(True, alpha=0.3)
ax.legend()
fig.tight_layout()

# Display the plot in Streamlit
st.pyplot(fig)
plt.close(fig)


st.subheader("Detected Peak Locations")

peak_df = df[df["is_peak"] == 1][
    ["time", "filtered_acceleration"]
]

if not peak_df.empty:
    st.dataframe(
        peak_df.rename(columns={
            "time": "Time (s)",
            "filtered_acceleration": "Filtered Acceleration"
        }),
        use_container_width=True,
        hide_index=True
    )
else:
    st.warning("No peaks were detected in this dataset.")

# Download processed data
st.download_button(
    label="Download Analysis CSV",
    data=df.to_csv(index=False).encode("utf-8"),
    file_name="analysis_result.csv",
    mime="text/csv"
)

st.caption(
    "Note: Detected peaks are not yet validated as actual jump counts. "
    "The rate shown here is peak rate, not verified jump-rope rate."
)
